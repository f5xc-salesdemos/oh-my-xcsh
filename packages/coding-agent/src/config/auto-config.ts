export interface GenerateModelsYmlOptions {
	/** API base path for the litellm provider (e.g. "/v1" or "/api/v1"). Defaults to "/v1". */
	apiBasePath?: string;
	/** When provided, write this literal API key value instead of the LITELLM_API_KEY env var reference. */
	apiKeyLiteral?: string;
}

/** Generate models.yml content for LiteLLM proxy. */
export function generateModelsYml(baseUrl: string, options?: GenerateModelsYmlOptions): string {
	const apiBase = options?.apiBasePath ?? "/v1";
	// When a literal API key is provided, double-quote it to handle YAML-significant
	// characters (: ! # { } [ ] ' " etc.). Escape backslashes and double quotes first.
	const apiKeyValue = options?.apiKeyLiteral
		? `"${options.apiKeyLiteral.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`
		: "LITELLM_API_KEY";
	const keyComment = options?.apiKeyLiteral
		? "# API key stored as literal value"
		: "# API key resolved from LITELLM_API_KEY env var at runtime";
	const lines = [
		GENERATED_LITELLM_MARKER,
		keyComment,
		`configVersion: ${CURRENT_CONFIG_VERSION}`,
		"providers:",
		"  anthropic:",
		`    baseUrl: "${baseUrl}/anthropic"`,
		`    apiKey: ${apiKeyValue}`,
		"    modelAllowlist:",
		"      - claude-opus-5",
		"      - claude-sonnet-5",
		"      - claude-haiku-4-5",
		"    picker:",
		"      groupId: litellm",
		"      groupLabel: LiteLLM",
		"      sectionLabel: Anthropic",
		"  litellm:",
		`    baseUrl: "${baseUrl}${apiBase}"`,
		`    apiKey: ${apiKeyValue}`,
		"    api: openai-completions",
		"    discovery:",
		"      type: openai-compat",
		"    modelAllowlist:",
		"      - gpt-5.6-sol",
		"      - gpt-5.6-terra",
		"      - gpt-5.6-luna",
		"    picker:",
		"      groupId: litellm",
		"      groupLabel: LiteLLM",
		"      sectionLabel: OpenAI",
		"    modelOverrides:",
		"      gpt-5.6-sol:",
		"        reasoning: true",
		"        input:",
		"          - text",
		"          - image",
		"        thinking:",
		"          mode: effort",
		"          defaultLevel: medium",
		"          supportedLevels:",
		"            - { effort: none, description: No reasoning }",
		"            - { effort: low, description: Light reasoning }",
		"            - { effort: medium, description: Balanced reasoning }",
		"            - { effort: high, description: Deep reasoning }",
		"            - { effort: xhigh, description: Very deep reasoning }",
		"            - { effort: max, description: Maximum reasoning }",
		"        contextWindow: 1050000",
		"        maxTokens: 128000",
		"        compat:",
		"          supportsTemperature: false",
	];

	lines.push("");
	return lines.join("\n");
}

/** Persist models.yml with owner-only permissions because it may contain a literal proxy credential. */
export async function writeLiteLLMModelsYml(filePath: string, content: string): Promise<void> {
	await fs.promises.mkdir(path.dirname(filePath), { recursive: true, mode: LITELLM_CONFIG_DIR_MODE });
	try {
		await fs.promises.chmod(filePath, LITELLM_MODELS_FILE_MODE);
	} catch (error) {
		if (!isEnoent(error)) throw error;
	}
	await fs.promises.writeFile(filePath, content, { encoding: "utf-8", mode: LITELLM_MODELS_FILE_MODE });
}

export interface LiteLLMConfig {
	baseUrl: string;
	apiKey: string;
	apiBasePath?: string;
}

/**
 * Read existing models.yml and extract the anthropic provider's base URL and API key.
 *
 * - baseUrl: strips `/anthropic` suffix to recover the root proxy URL
 * - apiKey: env var name → process.env lookup; shell-backed → fall back to env;
 *   otherwise literal
 * - Falls back to getLiteLLMBaseUrl() and $env.LITELLM_API_KEY when the file is
 *   missing or the anthropic block is incomplete
 */
export function readLiteLLMConfig(modelsPath: string): LiteLLMConfig | undefined {
	if (!fs.existsSync(modelsPath)) return undefined;

	const block = readProviderFromModelsYml("anthropic", modelsPath);
	const litellmBlock = readProviderFromModelsYml("litellm", modelsPath);

	const resolvedBaseUrl = block?.baseUrl ? block.baseUrl.replace(/\/anthropic\/?$/, "") : getLiteLLMBaseUrl();

	let resolvedApiKey: string | undefined;
	const apiKey = block?.apiKey;
	if (!apiKey) {
		resolvedApiKey = $env.LITELLM_API_KEY;
	} else if (apiKey.kind === "envVar") {
		resolvedApiKey = $envExact(apiKey.name) ?? $env.LITELLM_API_KEY;
	} else if (apiKey.kind === "shellSecret") {
		resolvedApiKey = $env.LITELLM_API_KEY;
	} else {
		resolvedApiKey = apiKey.value;
	}

	if (!resolvedBaseUrl || !resolvedApiKey) return undefined;

	const apiBasePath = litellmBlock?.baseUrl?.startsWith(resolvedBaseUrl)
		? litellmBlock.baseUrl.slice(resolvedBaseUrl.length) || undefined
		: undefined;

	return { baseUrl: resolvedBaseUrl, apiKey: resolvedApiKey, apiBasePath };
}

/**
 * The default model role is baked into the binary (settings-schema `modelRoles`
 * default) so a fresh install needs NO config.yml. Re-exported here for the
 * healer and tests; there is a single source of truth in settings-schema.
 */
export const DEFAULT_MODEL_ROLE_VALUE = DEFAULT_MODEL_ROLE;

/**
 * Generate config.yml for the LiteLLM proxy.
 *
 * The default model role is NOT written here — it ships in the binary
 * (settings-schema), so we never persist a model id that can go stale (the
 * failure mode behind the invalid-model / catalog-walk bugs). This only carries
 * settings that differ from the built-in schema defaults.
 */
export function generateConfigYml(): string {
	return [
		GENERATED_LITELLM_MARKER,
		"# The default model role ships in the binary — none is written here.",
		"providers:",
		"  image: openai",
		"  webSearch: anthropic",
		"",
	].join("\n");
}

/**
 * Provider prefixes that are never valid as a persisted runtime default.
 * `bench-instant` is the TTFT benchmark stand-in provider — it only registers
 * when XCSH_BENCH_EXTENSION is set, so a `bench-instant/*` default in a normal
 * worker is unresolvable and drops xcsh into the "first available model"
 * fallback (which can pick a model the F5 proxy can't serve).
 */
const UNRESOLVABLE_DEFAULT_PROVIDER_PREFIXES = ["bench-instant/"];

/**
 * Repair a config.yml whose `modelRoles.default` can never resolve at runtime
 * (e.g. `bench-instant/bench-instant` leaked from a benchmark run) by rewriting
 * it to the binary default. Left unhealed, such a default triggers the
 * catalog-wide fallback that surfaced as the AWS-SSO / invalid-model errors.
 *
 * A config.yml with NO `modelRoles:` needs no healing — the binary provides the
 * default. We deliberately do not add one, to avoid persisting a stale id.
 */
export function healConfigYmlModelRoles(configPath: string): void {
	try {
		hardenAgentConfigFileSync(configPath);
		const content = fs.readFileSync(configPath, "utf-8");
		if (!content.includes("modelRoles:")) return; // binary default applies
		const defaultLine = /^(\s*)default:\s*(\S+)\s*$/m;
		const match = content.match(defaultLine);
		if (match) {
			const [, indent, value] = match;
			if (UNRESOLVABLE_DEFAULT_PROVIDER_PREFIXES.some(prefix => value.startsWith(prefix))) {
				const healed = content.replace(defaultLine, `${indent}default: ${DEFAULT_MODEL_ROLE_VALUE}`);
				writeAgentConfigFileSync(configPath, healed);
				logger.debug("Healed config.yml: replaced unresolvable default modelRole", {
					configPath,
					previous: value,
					replacement: DEFAULT_MODEL_ROLE_VALUE,
				});
			}
		}
	} catch {
		// Best-effort — don't block startup
	}
}

