/**
 * Extract a double-quoted literal API key from an existing models.yml file.
 * Checks the anthropic and litellm provider blocks; returns undefined if
 * neither has a literal (e.g., both use env var references) or the file is
 * missing.
 */
export function readApiKeyLiteral(modelsPath: string): string | undefined {
	for (const name of ["anthropic", "litellm"]) {
		const block = readProviderFromModelsYml(name, modelsPath);
		if (block?.apiKey?.kind === "literal" && block.apiKey.wasQuoted) {
			return block.apiKey.value;
		}
	}
	return undefined;
}

/** Create an owner-only .bak backup of models.yml. Returns true if backed up. */
function backupModelsConfigIfExists(filePath: string): boolean {
	const backupPath = `${filePath}.bak`;
	try {
		return safeWriteModelsConfig(backupPath, fs.readFileSync(filePath));
	} catch (err) {
		if (!isEnoent(err)) logger.warn("Failed to create backup", { filePath, err });
	}
	return false;
}

/** Safely write a file, creating parent directories. */
function safeWrite(filePath: string, content: string): boolean {
	try {
		writeAgentConfigFileSync(filePath, content);
		return true;
	} catch (err) {
		logger.warn("Failed to write config file", { filePath, err });
		return false;
	}
}

/** Write models.yml content without ever exposing it through group/world-readable permissions. */
function safeWriteModelsConfig(filePath: string, content: string | Uint8Array): boolean {
	try {
		fs.mkdirSync(path.dirname(filePath), { recursive: true, mode: LITELLM_CONFIG_DIR_MODE });
		try {
			fs.chmodSync(filePath, LITELLM_MODELS_FILE_MODE);
		} catch (err) {
			if (!isEnoent(err)) throw err;
		}
		fs.writeFileSync(filePath, content, { encoding: "utf-8", mode: LITELLM_MODELS_FILE_MODE });
		return true;
	} catch (err) {
		logger.warn("Failed to write LiteLLM models config", { filePath, err });
		return false;
	}
}

/** Remove the model cache database so discovery re-runs fresh. */
function clearModelCache(modelsPath: string): void {
	const cacheDbPath = path.join(path.dirname(modelsPath), "models.db");
	try {
		if (fs.existsSync(cacheDbPath)) {
			fs.unlinkSync(cacheDbPath);
			logger.debug("Cleared stale model cache", { cacheDbPath });
		}
		// Also remove WAL/SHM files if present
		for (const suffix of ["-wal", "-shm"]) {
			const walPath = `${cacheDbPath}${suffix}`;
			if (fs.existsSync(walPath)) {
				fs.unlinkSync(walPath);
			}
		}
	} catch {
		// Best-effort — don't block config repair
	}
}

